/**
 * The seed each procedural job starts from, so the jobs can run in any order, in parallel,
 * and still draw the same random numbers the prototype drew when it painted them one after
 * the other on the main thread.
 *
 * It replays the prototype's order in Chromium (the notebook's handwriting makes the number
 * of draws depend on the font's widths, so it must measure real text) and writes
 * scene/seeds.js. The prototype's own numbers therefore came from the machine it ran on; the
 * table fixes them to this one's (macOS, where the owner approved the scene).
 *
 *   node test/server.mjs &   then   node tools/seeds.mjs
 *
 * Run it after changing how many random numbers any job draws, or the order of the scene.
 */
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const require = createRequire(resolve(import.meta.dirname, "../../../../../../plugins/frascella/package.json"));
const { chromium } = require("playwright");
const GEN = "/wp-content/themes/frascella/assets/src/desk/scene/gen.js";

async function sequence([GEN, shot]) {
    const G = await import(GEN);
    const S = shot ? 512 : 1024, at = {};
    G.setCanvasFactory((w, h) => new OffscreenCanvas(w, h));
    G.reseed(7);
    const job = (name, fn) => { at[name] = G.seedNow(); fn(); };
    job("smudge1", () => G.smudge(512));
    job("smudge2", () => G.smudge(512, { base: 235, depth: 40, blobs: 14 }));
    job("laminate", () => G.laminate(S));
    job("carpet", () => G.carpet(S));
    job("wall", () => G.wall(S));
    job("felt", () => G.felt(1024));
    // buildTools: where the screws lie (4 draws for each of the six in the tray, 2 for the three out)
    job("tools", () => { for (let i = 0; i < 9; i++) for (let k = 0; k < (i < 6 ? 4 : 2); k++) G.rnd(); });
    job("grain90", () => G.grain(256, 90));
    job("spread", () => G.spread());
    job("grain70", () => G.grain(256, 70));
    job("cork", () => G.cork());
    job("crema", () => G.crema());
    // buildPlant: gravel() in plant.js draws 32 per grain — r, a, s (two), cy; the euler (3); the
    // scale (3); the six vertices' jitter (18); glint, its grey, its tint. Keep in step with it.
    job("gravel", () => { for (let i = 0; i < 2700 * 32; i++) G.rnd(); });
    job("vinyl", () => G.vinyl());
    job("board", () => G.board(1024));
    at.sleeve = G.seedNow();
    return at;
}
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto("http://127.0.0.1:8790/wp-content/themes/frascella/assets/src/desk/tools/");
const out = {};
for (const shot of [false, true]) out[shot ? "shot" : "normal"] = await page.evaluate(sequence, [GEN, shot]);
await browser.close();
const file = resolve(import.meta.dirname, "../scene/seeds.js");
writeFileSync(file, `// Generated by tools/seeds.mjs: the seed each procedural job starts from (see gen.js). Do not edit.\nexport const SEEDS = ${JSON.stringify(out.normal)};\nexport const SEEDS_SHOT = ${JSON.stringify(out.shot)};\n`);
console.log(out);
